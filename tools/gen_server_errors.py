#!/usr/bin/env python3
"""Writes crates/serverclient/src/errors_table.rs from the error catalog of the EH3D server.

The codes and their statuses come from EH3D-SERVER/docs/error-codes.json; the texts (eight languages) come from the
rows `err_<code>` of EH3D-STUDIO/src/texts.ts, which are in the order English, Spanish, Italian, German, French,
European Portuguese, Chinese, Japanese. A code that Studio has no row for takes its eight texts from tools/server_error_texts_extra.json (a row of Studio always wins). A code without
eight texts in either place is an error: no text is ever invented here, and a row of the extra file for a code the catalog no longer has is an error too.

    py -3 tools/gen_server_errors.py          write the table
    py -3 tools/gen_server_errors.py --check  fail when the table on disk is not the one the sources give
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GITHUB = ROOT.parent
CODES = GITHUB / "EH3D-SERVER" / "docs" / "error-codes.json"
TEXTS = GITHUB / "EH3D-STUDIO" / "src" / "texts.ts"
EXTRA = ROOT / "tools" / "server_error_texts_extra.json"
OUT = ROOT / "crates" / "serverclient" / "src" / "errors_table.rs"
ROW = re.compile(r'^\s*err_([a-z0-9_]+):\s*\[(.*)\],?\s*$')
STR = re.compile(r'"((?:[^"\\]|\\.)*)"')


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build() -> str:
    codes = json.loads(CODES.read_text(encoding="utf-8"))
    rows = {}
    for line in TEXTS.read_text(encoding="utf-8").splitlines():
        m = ROW.match(line)
        if m:
            vals = [json.loads('"' + v + '"') for v in STR.findall(m.group(2))]
            rows[m.group(1)] = vals
    extra = {k: v for k, v in json.loads(EXTRA.read_text(encoding="utf-8")).items() if not k.startswith("_")}
    stale = sorted(set(extra) - {i["code"] for i in codes})
    if stale:
        sys.exit("rows of the extra file for codes the catalog does not have: " + ", ".join(stale))
    out = [
        "// Generated by tools/gen_server_errors.py from the error catalog of the server, the texts of Studio and tools/server_error_texts_extra.json; do not edit by hand.",
        "// Languages in each row: en, es, it, de, fr, pt, zh, ja.",
        "use crate::errors::ErrorEntry;",
        "",
        "#[rustfmt::skip]",
        "pub(crate) static TABLE: &[ErrorEntry] = &[",
    ]
    missing = []
    for item in sorted(codes, key=lambda i: i["code"]):
        code = item["code"]
        vals = rows.get(code) or extra.get(code)
        if not vals or len(vals) != 8:
            missing.append(code)
            continue
        out.append("    ErrorEntry {")
        out.append(f"        code: {rust_str(code)},")
        out.append(f"        status: {item['status']},")
        out.append("        texts: [")
        for v in vals:
            out.append(f"            {rust_str(v)},")
        out.append("        ],")
        out.append("    },")
    if missing:
        sys.exit("codes without eight texts in Studio or in the extra file: " + ", ".join(missing))
    out.append("];")
    return "\n".join(out) + "\n"


def main() -> None:
    text = build()
    if "--check" in sys.argv:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have.replace("\r\n", "\n") != text:
            sys.exit("errors_table.rs is not the one the catalog gives: run tools/gen_server_errors.py (then rustfmt)")
        print("PASS errors_table.rs matches the catalog")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
